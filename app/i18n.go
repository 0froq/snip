package app

// tr returns a UI string for lang (en or zh). Unknown keys return the key.
func tr(lang, key string) string {
	table := en
	if lang == "zh" || lang == "zh-CN" || lang == "zh-Hans" {
		table = zh
	}
	if s, ok := table[key]; ok {
		return s
	}
	if s, ok := en[key]; ok {
		return s
	}
	return key
}

