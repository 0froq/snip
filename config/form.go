// Parse validates the draft and merges it onto prev.
func (f Form) Parse(prev Config) (Config, error) {
	cfg := prev
	var err error
	if cfg.ClipboardPollMs, err = positiveInt(f.ClipboardPollMs, "Poll interval"); err != nil {
		return Config{}, err
	}
	if cfg.MaxCards, err = positiveInt(f.MaxCards, "Max cards"); err != nil {
		return Config{}, err
	}
	cfg.Window.AlwaysOnTop = f.AlwaysOnTop
	cfg.Window.VisibleOnAllWorkspaces = f.VisibleOnAllWorkspaces
	cfg.Window.ContentProtection = f.ContentProtection
	panel := f.Panel
	cfg.Window.Panel = &panel
	place := strings.ToLower(strings.TrimSpace(f.Placement))
	switch place {
	case "near-selection", "near-cursor", "fixed":
		cfg.Card.Placement = place
	default:
		return Config{}, fmt.Errorf("placement must be near-selection, near-cursor, or fixed")
	}
	ints := []struct {
		dst  *int
		raw  string
		name string
	}{
		{&cfg.Card.MinWidth, f.MinWidth, "Min width"},
		{&cfg.Card.MaxWidth, f.MaxWidth, "Max width"},
		{&cfg.Card.Height, f.Height, "Height"},
		{&cfg.Card.MaxHeight, f.MaxHeight, "Max height"},
		{&cfg.Card.LineHeight, f.LineHeight, "Line height"},
		{&cfg.Card.MaxLines, f.MaxLines, "Max lines"},
		{&cfg.Card.PaddingX, f.PaddingX, "Padding x"},
		{&cfg.Card.PaddingY, f.PaddingY, "Padding y"},
		{&cfg.Card.FontSize, f.FontSize, "Font size"},
		{&cfg.Card.CharWidth, f.CharWidth, "Char width"},
		{&cfg.Card.CascadeOriginX, f.CascadeOriginX, "Cascade origin x"},
		{&cfg.Card.CascadeOriginY, f.CascadeOriginY, "Cascade origin y"},
		{&cfg.Card.CascadeStepX, f.CascadeStepX, "Cascade step x"},
		{&cfg.Card.CascadeStepY, f.CascadeStepY, "Cascade step y"},
	}
	for _, item := range ints {
		n, err := nonNegativeInt(item.raw, item.name)
		if err != nil {
			return Config{}, err
		}
		*item.dst = n
	}
	if cfg.Card.MinWidth > cfg.Card.MaxWidth {
		return Config{}, fmt.Errorf("min width cannot be larger than max width")
	}
	cfg.Card.ActiveColor = strings.TrimSpace(f.ActiveColor)
	cfg.Shortcuts.Toggle = strings.TrimSpace(f.Toggle)
	cfg.Shortcuts.Direct = f.Direct
	cfg.Shortcuts.Pin = strings.TrimSpace(f.Pin)
	cfg.Shortcuts.Next = strings.TrimSpace(f.Next)
	cfg.Shortcuts.Prev = strings.TrimSpace(f.Prev)
	cfg.Shortcuts.Paste = strings.TrimSpace(f.Paste)
	cfg.Shortcuts.Delete = strings.TrimSpace(f.Delete)
	cfg.Shortcuts.Settings = strings.TrimSpace(f.Settings)
	cfg.Secrets.MaskEnabled = f.MaskEnabled
	cfg.Secrets.ExtraPatterns = nil
	for _, line := range strings.Split(f.ExtraPatterns, "\n") {
		line = strings.TrimSpace(line)
		if line != "" {
			cfg.Secrets.ExtraPatterns = append(cfg.Secrets.ExtraPatterns, line)
		}
	}
	bits, err := strconv.ParseFloat(strings.TrimSpace(f.MinEntropyBits), 64)
	if err != nil || bits < 0 {
		return Config{}, fmt.Errorf("min entropy must be a number that is zero or more")
	}
	cfg.Secrets.MinEntropyBits = bits
	if cfg.Secrets.MinSecretLength, err = nonNegativeInt(f.MinSecretLength, "Min secret length"); err != nil {
		return Config{}, err
	}
	cfg.Pasteboard = Pasteboard{
		HonorConcealed:    f.HonorConcealed,
		SkipTransient:     f.SkipTransient,
		SkipAutoGenerated: f.SkipAutoGenerated,
	}
	timeout, err := positiveInt(f.LeaderTimeout, "Leader timeout")
	if err != nil {
		return Config{}, err
	}
	gap, err := positiveInt(f.DoublePressMs, "Double press interval")
	if err != nil {
		return Config{}, err
	}
	motionMs, err := positiveInt(f.MotionMs, "Animation duration")
	if err != nil {
		return Config{}, err
	}
	cfg.Leader.Shortcut = strings.TrimSpace(f.LeaderShortcut)
	cfg.Leader.TimeoutMs = timeout
	cfg.Leader.Toggle = strings.TrimSpace(f.LeaderToggle)
	cfg.Leader.Next = strings.TrimSpace(f.LeaderNext)
	cfg.Leader.Prev = strings.TrimSpace(f.LeaderPrev)
	cfg.Leader.Paste = strings.TrimSpace(f.LeaderPaste)
	cfg.Leader.Delete = strings.TrimSpace(f.LeaderDelete)
	cfg.Leader.Pin = strings.TrimSpace(f.LeaderPin)
	cfg.Leader.Settings = strings.TrimSpace(f.LeaderSettings)
	cfg.Leader.DoublePressMs = gap
	cfg.Leader.Double = parseDouble(f.DoubleMap)
	cfg.Leader.DimOverlay = f.DimOverlay
	cfg.Motion.Enabled = f.MotionEnabled
	cfg.Motion.DurationMs = motionMs
	lang := strings.TrimSpace(f.Language)
	if lang == "" {
		lang = "en"
	}
	if lang != "en" && lang != "zh" {
		return Config{}, fmt.Errorf("language must be en or zh")
	}
	cfg.Language = lang
	return cfg, nil
}

func formatDouble(m map[string]string) string {
	if len(m) == 0 {
		return ""
	}
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	sortStrings(keys)
	var b strings.Builder
	for _, k := range keys {
		if b.Len() > 0 {
			b.WriteByte('\n')
		}
		b.WriteString(k)
		b.WriteByte('=')
		b.WriteString(m[k])
	}
	return b.String()
}

func parseDouble(s string) map[string]string {
	out := map[string]string{}
	for _, line := range strings.Split(s, "\n") {
		line = strings.TrimSpace(line)
		if line == "" {
			continue
		}
		key, val, ok := strings.Cut(line, "=")
		if !ok {
			continue
		}
		key = strings.ToLower(strings.TrimSpace(key))
		val = strings.TrimSpace(val)
		if key != "" && val != "" {
			out[key] = val
		}
	}
	return out
}

func sortStrings(s []string) {
	for i := 1; i < len(s); i++ {
		for j := i; j > 0 && s[j] < s[j-1]; j-- {
			s[j], s[j-1] = s[j-1], s[j]
		}
	}
}

// NeedsRestart reports window options that only apply to new card windows.
func NeedsRestart(prev, next Config) bool {
	return prev.Window.EffectiveFrameless() != next.Window.EffectiveFrameless() ||
		prev.Window.EffectivePanel() != next.Window.EffectivePanel()
}

// Save writes cfg as TOML, creating parent directories when needed.
func Save(path string, cfg Config) error {
	if dir := filepath.Dir(path); dir != "" && dir != "." {
		if err := os.MkdirAll(dir, 0o755); err != nil {
			return err
		}
	}
	f, err := os.Create(path)
	if err != nil {
		return err
	}
	defer f.Close()
	return toml.NewEncoder(f).Encode(normalizeForSave(cfg))
}

// normalizeForSave omits window keys that match built in defaults so a
// settings save does not pin advanced values the UI never touched.
func normalizeForSave(cfg Config) Config {
	if cfg.Window.EffectiveFrameless() {
		cfg.Window.Frameless = nil
	}
	if cfg.Window.EffectivePanel() {
		cfg.Window.Panel = nil
	}
	return cfg
}

func positiveInt(raw, name string) (int, error) {
	n, err := strconv.Atoi(strings.TrimSpace(raw))
	if err != nil || n <= 0 {
		return 0, fmt.Errorf("%s must be a whole number greater than zero", name)
	}
	return n, nil
}

func nonNegativeInt(raw, name string) (int, error) {
	n, err := strconv.Atoi(strings.TrimSpace(raw))
	if err != nil || n < 0 {
		return 0, fmt.Errorf("%s must be a whole number that is zero or more", name)
	}
	return n, nil
}
