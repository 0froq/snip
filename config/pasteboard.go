package config

import "github.com/0froq/snip/internal/macpaste"

// Pasteboard controls handling of org.nspasteboard.org marker types.
type Pasteboard struct {
	HonorConcealed     bool `toml:"honor_concealed"`
	SkipTransient      bool `toml:"skip_transient"`
	SkipAutoGenerated  bool `toml:"skip_auto_generated"`
}

// DefaultPasteboard returns marker handling defaults (all enabled).
func DefaultPasteboard() Pasteboard {
	return Pasteboard{
		HonorConcealed:    true,
		SkipTransient:     true,
		SkipAutoGenerated: true,
	}
}

// SkipClipboardChange reports whether a copy should not spawn a card.
func (p Pasteboard) SkipClipboardChange(m macpaste.Markers) bool {
	if p.SkipTransient && m.Transient {
		return true
	}
	if p.SkipAutoGenerated && m.AutoGenerated {
		return true
	}
	return false
}

// ConcealedOnCard reports whether the copy should be fully masked on the card.
func (p Pasteboard) ConcealedOnCard(m macpaste.Markers) bool {
	return p.HonorConcealed && m.Concealed
}
