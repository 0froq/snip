//go:build darwin

package macpaste

// ReadMarkers inspects the general pasteboard for org.nspasteboard.org types.
func ReadMarkers() Markers {
	load()
	var m Markers
	withPool(func() {
		pb := pasteboard()
		m.Concealed = hasType(pb, TypeConcealed)
		m.Transient = hasType(pb, TypeTransient)
		m.AutoGenerated = hasType(pb, TypeAutoGenerated)
	})
	return m
}

func hasType(pb id, uti string) bool {
	types := send(pb, "types")
	if types == 0 {
		return false
	}
	want := goString(nsString(uti))
	n := sendInt(types, "count")
	for i := 0; i < n; i++ {
		if goString(send(types, "objectAtIndex:", uintptr(i))) == want {
			return true
		}
	}
	return false
}
